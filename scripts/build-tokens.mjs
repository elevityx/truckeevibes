// Generates src/styles/tokens.css from src/styles/tokens.json (the approved design tokens).
//   node scripts/build-tokens.mjs                write the css
//   node scripts/build-tokens.mjs --check        compare; exit 1 naming the first differing line
// Test hooks: --tokens <path> and --css <path> override the two file locations.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const HEADER = '/* generated by scripts/build-tokens.mjs from tokens.json; do not edit */';

/** @param {any} t parsed tokens.json  @returns {string} the css text */
export function generate(t) {
  const colors = t.color.tokens;
  const shadows = t.shadow.tokens;
  const out = [HEADER, ':root{', '  color-scheme:light dark;'];
  for (const c of colors) out.push(`  --${c.name}:${c.value.daylight};`);
  for (const g of t.type.groups) {
    for (const s of g.styles) {
      out.push(`  --fs-${s.name}:${s.fontSize};`, `  --lh-${s.name}:${s.lineHeight};`, `  --fw-${s.name}:${s.fontWeight};`);
      if (s.letterSpacing) out.push(`  --ls-${s.name}:${s.letterSpacing};`);
    }
  }
  out.push(
    '  --font-display:var(--font-bricolage), "Atkinson Hyperlegible Next", system-ui, sans-serif;',
    '  --font-body:var(--font-atkinson), system-ui, -apple-system, "Segoe UI", sans-serif;',
  );
  for (const s of t.spacing.tokens) out.push(`  --${s.name}:${s.value};`);
  for (const r of t.radius.tokens) out.push(`  --${r.name}:${r.value};`);
  for (const s of shadows) out.push(`  --${s.name}:${s.value.daylight};`);
  out.push('  --motion-duration:180ms;', '  --motion-ease:cubic-bezier(0,0,.2,1);', '}');
  out.push('@media (prefers-color-scheme: dark){', '  :root{');
  for (const c of colors) out.push(`    --${c.name}:${c.value.afterdark};`);
  for (const s of shadows) out.push(`    --${s.name}:${s.value.afterdark};`);
  out.push('  }', '}');
  out.push('@media (prefers-reduced-motion: reduce){', '  *,*::before,*::after{transition:none!important;animation:none!important}', '}', '');
  return out.join('\n');
}

function main(argv) {
  const opt = (name, dflt) => (argv.includes(name) ? argv[argv.indexOf(name) + 1] : dflt);
  const tokensPath = opt('--tokens', join(ROOT, 'src/styles/tokens.json'));
  const cssPath = opt('--css', join(ROOT, 'src/styles/tokens.css'));
  const css = generate(JSON.parse(readFileSync(tokensPath, 'utf8')));
  if (!argv.includes('--check')) {
    writeFileSync(cssPath, css);
    console.log(`build-tokens: wrote ${cssPath}`);
    return 0;
  }
  let have;
  try {
    have = readFileSync(cssPath, 'utf8');
  } catch {
    console.error(`build-tokens: ${cssPath} is missing; run node scripts/build-tokens.mjs`);
    return 1;
  }
  if (have === css) {
    console.log('build-tokens: ok');
    return 0;
  }
  const a = css.split('\n');
  const b = have.split('\n');
  for (let i = 0; i < Math.max(a.length, b.length); i++) {
    if (a[i] !== b[i]) {
      console.error(`build-tokens: tokens.css is stale at line ${i + 1}: expected "${(a[i] ?? '').trim()}" but found "${(b[i] ?? '').trim()}"; run node scripts/build-tokens.mjs`);
      return 1;
    }
  }
  return 1;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) process.exit(main(process.argv.slice(2)));
