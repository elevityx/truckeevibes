// AC-R1a-01, AC-R1a-02
import { describe, expect, it } from 'vitest';
import { spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { REPO_ROOT } from './_testlib.mjs';

const script = join(REPO_ROOT, 'scripts/build-tokens.mjs');
const run = (...args) => {
  const r = spawnSync('node', [script, ...args], { cwd: REPO_ROOT, encoding: 'utf8' });
  return { status: r.status, out: `${r.stdout}${r.stderr}` };
};
const css = readFileSync(join(REPO_ROOT, 'src/styles/tokens.css'), 'utf8');
const tokens = JSON.parse(readFileSync(join(REPO_ROOT, 'src/styles/tokens.json'), 'utf8'));
const dark = css.slice(css.indexOf('@media (prefers-color-scheme: dark)'), css.indexOf('@media (prefers-reduced-motion'));
const light = css.slice(0, css.indexOf('@media (prefers-color-scheme: dark)'));

describe('AC-R1a-01 build-tokens --check', () => {
  it('passes on the committed tree', () => expect(run('--check').status).toBe(0));
  it('fails and names --ground when ground changes in a temp copy of tokens.json', () => {
    const t = structuredClone(tokens);
    t.color.tokens.find((c) => c.name === 'ground').value.daylight = '#010203';
    const dir = mkdtempSync(join(tmpdir(), 'tv-tok-'));
    const p = join(dir, 'tokens.json');
    writeFileSync(p, JSON.stringify(t));
    const r = run('--check', '--tokens', p);
    expect(r.status).toBe(1);
    expect(r.out).toContain('--ground');
  });
});

describe('AC-R1a-02 tokens.css content', () => {
  it('has the generated header', () =>
    expect(css.startsWith('/* generated by scripts/build-tokens.mjs from tokens.json; do not edit */')).toBe(true));
  it('declares all 17 colors in both themes', () => {
    expect(tokens.color.tokens).toHaveLength(17);
    for (const c of tokens.color.tokens) {
      expect(light).toContain(`--${c.name}:${c.value.daylight};`);
      expect(dark).toContain(`--${c.name}:${c.value.afterdark};`);
    }
    expect(light).toContain('color-scheme:light dark;');
  });
  it('declares every type style', () => {
    for (const g of tokens.type.groups)
      for (const s of g.styles) {
        expect(css).toContain(`--fs-${s.name}:${s.fontSize};`);
        expect(css).toContain(`--lh-${s.name}:${s.lineHeight};`);
        expect(css).toContain(`--fw-${s.name}:${s.fontWeight};`);
        if (s.letterSpacing) expect(css).toContain(`--ls-${s.name}:${s.letterSpacing};`);
      }
    expect(css).toContain('--fs-hero:44px;');
    expect(css).toContain('--lh-hero:46px;');
    expect(css).toContain('--fs-tag:11.5px;');
    expect(css).toContain('--font-display:var(--font-bricolage)');
    expect(css).toContain('--font-body:var(--font-atkinson)');
  });
  it('declares spacing, radii and both shadows in both themes', () => {
    expect(css).toContain('--space-1:4px;');
    expect(css).toContain('--space-12:48px;');
    for (const r of ['sm', 'md', 'lg', 'sheet', 'pill']) expect(css).toContain(`--radius-${r}:`);
    for (const s of tokens.shadow.tokens) {
      expect(light).toContain(`--${s.name}:${s.value.daylight};`);
      expect(dark).toContain(`--${s.name}:${s.value.afterdark};`);
    }
  });
  it('declares motion and the reduced-motion block', () => {
    expect(css).toContain('--motion-duration:180ms;');
    expect(css).toMatch(/@media \(prefers-reduced-motion: reduce\)\{[^}]*\{[^}]*transition:none!important/s);
  });
});
