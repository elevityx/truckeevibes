-- A7-2: weekly owner minutes for the admin console. The expression is svc_weekly_report()'s review_minutes_7d verbatim
-- (20261020000400_jobs.sql), so the console and the weekly email agree by construction. Rolling 7 days.
create function public.admin_owner_minutes_7d() returns numeric
language plpgsql stable security definer set search_path = '' as $$
begin
  if not private.is_admin() then raise exception 'forbidden' using errcode = '42501'; end if;
  return round(((select coalesce(sum(c.review_seconds), 0) from public.review_cards c
                  where c.decided_by is not null and c.decided_at > now() - interval '7 days')
              + (select coalesce(sum(a.seconds), 0) from public.owner_activity a
                  where a.at > now() - interval '7 days')) / 60.0, 1);
end $$;

